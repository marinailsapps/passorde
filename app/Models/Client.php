<?php

namespace App\Models;

use App\Enums\ClientSource;
use App\Enums\OrderStatus;
use App\Support\SyncMode;
use Database\Factories\ClientFactory;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Support\Carbon;

/**
 * @property int $id
 * @property string|null $uuid
 * @property int|null $evoliz_client_id
 * @property string|null $evoliz_code
 * @property string|null $evoliz_error
 * @property string $company_name
 * @property string|null $contact_name
 * @property string|null $address_line
 * @property string|null $postcode
 * @property string|null $town
 * @property string|null $phone
 * @property string|null $mobile
 * @property string|null $email
 * @property string|null $extra_field
 * @property ClientSource $source
 * @property bool $is_active
 * @property int|null $created_by
 * @property Carbon|null $synced_at
 */
class Client extends Model
{
    /** @use HasFactory<ClientFactory> */
    use HasFactory;

    protected $fillable = [
        'uuid',
        'evoliz_client_id',
        'evoliz_code',
        'evoliz_error',
        'company_name',
        'contact_name',
        'address_line',
        'postcode',
        'town',
        'phone',
        'mobile',
        'email',
        'extra_field',
        'source',
        'is_active',
        'created_by',
        'synced_at',
    ];

    /**
     * Generated by PostgreSQL; never selected into the model.
     *
     * @var list<string>
     */
    protected $hidden = ['search_vector', 'phone_digits'];

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'evoliz_client_id' => 'integer',
            'source' => ClientSource::class,
            'is_active' => 'boolean',
            'synced_at' => 'datetime',
        ];
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function creator(): BelongsTo
    {
        return $this->belongsTo(User::class, 'created_by');
    }

    /**
     * @return HasMany<Order, $this>
     */
    public function orders(): HasMany
    {
        return $this->hasMany(Order::class);
    }

    /**
     * @return HasMany<ClientChange, $this>
     */
    public function changes(): HasMany
    {
        return $this->hasMany(ClientChange::class);
    }

    public function isLinkedToEvoliz(): bool
    {
        return $this->evoliz_client_id !== null;
    }

    /**
     * A settled entry of the client directory, the API's "linked": in Evoliz. In
     * file mode there is no Evoliz: imported, or typed with an order past pending.
     * Asks the database only for a typed client in file mode.
     */
    public function isSettled(): bool
    {
        if ($this->isLinkedToEvoliz()) {
            return true;
        }

        if (! SyncMode::isFile()) {
            return false;
        }

        return $this->source !== ClientSource::App || $this->orders()->whereNot('status', OrderStatus::Pending)->exists();
    }

    /** Typed in the app and not settled yet: its author may still change it. */
    public function isOpenTypedClient(): bool
    {
        return $this->source === ClientSource::App && ! $this->isSettled();
    }
}
