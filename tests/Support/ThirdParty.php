<?php

namespace Tests\Support;

/**
 * THIRD-PARTY.md, built from the lock files: the PHP packages a production install gets (composer.lock
 * "packages", without the dev ones) and the npm packages the built front end is made from (every package that
 * resources/js or resources/css imports, with its dependencies as package-lock.json resolves them; a superset of
 * what the bundle holds, plus Vite's module preload helper, which the build adds for the dynamic import of
 * workbox-window). Written by scripts/third-party.php; tests/Feature/ThirdPartyTest.php fails when the file is
 * stale. A development tool: it lives with the tests and is not shipped code.
 */
final class ThirdParty
{
    public static function markdown(string $base): string
    {
        $lines = [
            '# Third-party components',
            '',
            'Generated by `php scripts/third-party.php` from `composer.lock` and `package-lock.json`; do not edit by hand.',
            '',
            'Passorde does not copy these components into its repository: Composer and npm install them from their own sources, each under its own licence. The versions are those of the lock files.',
            '',
            '## PHP packages (production install, `composer install --no-dev`)',
            '',
            '| Package | Version | Licence |',
            '| --- | --- | --- |',
        ];
        foreach (self::composer($base) as [$name, $version, $licence]) {
            $lines[] = "| {$name} | {$version} | {$licence} |";
        }
        $lines = [...$lines, '',
            'Passorde Connect (`marinailsapps/passorde-connect`) is under its own proprietary licence: `vendor/marinailsapps/passorde-connect/LICENSE.md` once installed, and `LICENSE.md` in its public repository, https://github.com/marinailsapps/passorde-connect.',
            '', '## npm packages of the built front end (a superset of the bundle)', '',
            'The packages the front end imports, with their dependencies as `package-lock.json` resolves them: a superset of what the built bundle holds (some are only used by the build), plus Vite\'s module preload helper, which the build adds to the bundle.',
            '', '| Package | Version | Licence |', '| --- | --- | --- |'];
        foreach (self::npm($base) as [$name, $version, $licence]) {
            $lines[] = "| {$name} | {$version} | {$licence} |";
        }

        return implode("\n", $lines)."\n";
    }

    /** @return list<array{string, string, string}> */
    private static function composer(string $base): array
    {
        /** @var array{packages: list<array{name: string, version: string, license?: list<string>}>} $lock */
        $lock = json_decode((string) file_get_contents($base.'/composer.lock'), true, flags: JSON_THROW_ON_ERROR);
        $rows = array_map(fn (array $package) => [$package['name'], $package['version'], implode(' OR ', $package['license'] ?? []) ?: 'unknown'], $lock['packages']);
        usort($rows, fn (array $a, array $b) => strcmp($a[0], $b[0]));

        return $rows;
    }

    /** @return list<array{string, string, string}> */
    private static function npm(string $base): array
    {
        /** @var array<string, array{version?: string, license?: string, dependencies?: array<string, string>, optionalDependencies?: array<string, string>}> $packages */
        $packages = json_decode((string) file_get_contents($base.'/package-lock.json'), true, flags: JSON_THROW_ON_ERROR)['packages'];

        $found = [];
        $queue = array_map(fn (string $name) => "node_modules/{$name}", array_filter(self::imported($base), fn (string $name) => isset($packages["node_modules/{$name}"])));
        while ($queue !== []) {
            $path = array_shift($queue);
            if (isset($found[$path])) {
                continue;
            }
            $found[$path] = true;
            foreach (array_keys([...$packages[$path]['dependencies'] ?? [], ...$packages[$path]['optionalDependencies'] ?? []]) as $dependency) {
                // Node's lookup: the nearest node_modules up the tree that has it.
                for ($dir = $path; ; $dir = (string) preg_replace('#/node_modules/(@[^/]+/)?[^/]+$#', '', $dir)) {
                    if (isset($packages["{$dir}/node_modules/{$dependency}"])) {
                        $queue[] = "{$dir}/node_modules/{$dependency}";
                        break;
                    }
                    if (! str_contains($dir, '/node_modules/')) {
                        if (isset($packages["node_modules/{$dependency}"])) {
                            $queue[] = "node_modules/{$dependency}";
                        }
                        break;
                    }
                }
            }
        }

        $rows = [];
        foreach (array_keys($found) as $path) {
            $name = (string) preg_replace('#^.*node_modules/#', '', $path);
            $rows["{$name}@{$packages[$path]['version']}"] = [$name, (string) ($packages[$path]['version'] ?? ''), (string) ($packages[$path]['license'] ?? 'unknown')];
        }
        $vite = $packages['node_modules/vite'];
        $rows['vite (module preload helper)'] = ['vite (module preload helper)', (string) ($vite['version'] ?? ''), (string) ($vite['license'] ?? 'unknown')];
        ksort($rows);

        return array_values($rows);
    }

    /**
     * The npm packages named by an import in the front end's own code (tests left out).
     *
     * @return list<string>
     */
    private static function imported(string $base): array
    {
        $names = [];
        foreach (['resources/js', 'resources/css'] as $dir) {
            $files = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($base.'/'.$dir, \FilesystemIterator::SKIP_DOTS));
            foreach ($files as $file) {
                $path = $file->getPathname();
                if (! preg_match('/\.(ts|vue|css)$/', $path) || str_ends_with($path, '.test.ts')) {
                    continue;
                }
                preg_match_all('/(?:\bfrom|\bimport|@import)\s*\(?\s*[\'"]((?:@[\w.-]+\/)?[\w.-]+)[^\'"]*[\'"]/', (string) file_get_contents($path), $matches);
                foreach ($matches[1] as $name) {
                    $names[$name] = true;
                }
            }
        }
        $names = array_keys($names);
        sort($names);

        return $names;
    }
}
